/**
 * French locale (fr) - the pilot for the v4.1 locale layer (ADR-008).
 *
 * Sources (quoted in docs/LOCALES.md): Académie-français-aligned grammar
 * references - quatre-vingts/cent take -s only when multiplied AND nothing
 * follows ("quatre-vingts", "quatre-vingt-un"; "deux cents", "deux cent un");
 * "mille" is invariable; 71 = "soixante et onze" but 91 = "quatre-vingt-onze"
 * (no "et" after vingt); "cent un" has no "et"; long scale (milliard = 10^9,
 * billion = 10^12, billiard = 10^15 ...) with plural -s on scale words above 1;
 * ordinals in -ième with premier/neuvième/cinquième irregulars and
 * "vingt et unième"-style compounds.
 *
 * Orthography choice (documented): TRADITIONAL spelling (pre-1990-reform
 * spacing: "vingt et un", "cent trois"), which remains the widely accepted
 * form; the reform's universal hyphens were deliberately NOT adopted.
 * Number words are lowercase per French convention (the library's sentence
 * embeds them mid-sentence; en stays capitalized as its own convention).
 *
 * Words for 0..99 are GENERATED by the rules below (never hand-typed) so the
 * tens logic exists in exactly one place. Decimal-place ordinals ("dixièmes",
 * "milliardièmes" on the long scale) are localized via `decimalOrdinal`.
 */

import { illionName } from "../illions.js";
import type { LocaleDefinition } from "./types.js";

const UNITS = [
  "zéro",
  "un",
  "deux",
  "trois",
  "quatre",
  "cinq",
  "six",
  "sept",
  "huit",
  "neuf",
] as const;

const TEENS = [
  "dix",
  "onze",
  "douze",
  "treize",
  "quatorze",
  "quinze",
  "seize",
  "dix-sept",
  "dix-huit",
  "dix-neuf",
] as const;

const TENS = ["vingt", "trente", "quarante", "cinquante", "soixante"] as const;

/** Builds the 0..99 word table from the verified rules. */
function buildSmallNumbers(): string[] {
  const table: string[] = [...UNITS, ...TEENS];

  for (const [tensIndex, stem] of TENS.entries()) {
    const base = 20 + tensIndex * 10;
    table[base] = stem; // 20, 30, 40, 50, 60
    table[base + 1] = `${stem} et un`; // the only "et" case below 70
    for (let unit = 2; unit <= 9; unit++) {
      table[base + unit] = `${stem}-${UNITS[unit]}`;
    }
  }

  // 70s: soixante + teens ("soixante-dix", "soixante et onze", "soixante-douze"...)
  table[70] = "soixante-dix";
  table[71] = "soixante et onze";
  for (let unit = 2; unit <= 9; unit++) {
    table[70 + unit] = `soixante-${TEENS[unit]}`;
  }

  // 80s: quatre-vingts (plural only when nothing follows), else quatre-vingt-*
  table[80] = "quatre-vingts";
  for (let unit = 1; unit <= 9; unit++) {
    table[80 + unit] = `quatre-vingt-${UNITS[unit]}`;
  }

  // 90s: quatre-vingt + teens ("quatre-vingt-dix", "quatre-vingt-onze", ...)
  table[90] = "quatre-vingt-dix";
  for (let unit = 1; unit <= 9; unit++) {
    table[90 + unit] = `quatre-vingt-${TEENS[unit]}`;
  }

  return table;
}

/** French long scale: group index i >= 2 -> million/milliard/billion/billiard/... */
function frScaleWord(groupIndex: number, groupValue: number, groupWords: string): string {
  const k = groupIndex - 2; // 0 -> million (10^6), 1 -> milliard (10^9), ...
  const base = illionName(Math.floor(k / 2) + 1).toLowerCase();
  const singular = k % 2 === 0 ? base : base.replace(/illion$/, "illiard");
  const scale = groupValue === 1 ? singular : `${singular}s`;
  return `${groupWords} ${scale}`; // group-first: "cent vingt-trois millions"
}

const frSmall = (value: number): string => FR_SMALL_NUMBERS[value] as string;

/** Hundreds phrase shared by groupWord (via hundredPhraseFor) and the thousands phrase. */
function hundredPhrase(hundreds: number, remainder: number): string {
  return hundreds === 1 ? "cent" : `${frSmall(hundreds)} ${remainder === 0 ? "cents" : "cent"}`;
}

/** Ordinal of a full cardinal sentence: premier/unième/ième family + article rule. */
function frOrdinalize(cardinal: string): string {
  if (cardinal === "un") {
    return "premier"; // 1st is the special premier form
  }
  const words = cardinal.split(" ");
  const lastWord = words[words.length - 1] ?? cardinal;
  const parts = lastWord.split("-");
  const lastPart = parts[parts.length - 1] ?? lastWord;
  parts[parts.length - 1] = frOrdinalizeWord(lastPart);
  words[words.length - 1] = parts.join("-");

  let result = words.join(" ");
  // French drops the article on scale ordinals: "un million" -> "millionième".
  if (words.length === 2 && words[0] === "un") {
    result = result.slice(3);
  }
  return result;
}

function frOrdinalizeWord(word: string): string {
  if (word === "un") {
    return "unième"; // compound trailing: "vingt et unième"
  }
  if (word.endsWith("neuf")) {
    return `${word.slice(0, -1)}vième`; // neuf -> neuvième (f -> v)
  }
  if (word.endsWith("cinq")) {
    return `${word}uième`; // cinq -> cinquième (vingt-cinq -> vingt-cinquième)
  }
  if (word.endsWith("ts")) {
    return `${word.slice(0, -1)}ième`; // quatre-vingts -> quatre-vingtième
  }
  if (word.endsWith("e")) {
    return `${word.slice(0, -1)}ième`; // onze -> onzième, mille -> millième
  }
  return `${word}ième`; // six -> sixième, trois -> troisième, million -> millionième
}

export const FR_SMALL_NUMBERS: string[] = buildSmallNumbers();

/**
 * French decimal-place ordinals (SPEC: docs/LOCALES.md fr row + same sources
 * as the cardinals). The denominator follows the LONG scale:
 * 10^-3 millième, 10^-6 millionième, 10^-9 milliardième, 10^-12 billionième,
 * 10^-15 billiardième ... i.e. p = 3k + r with k even -> -illion, k odd ->
 * -illiard, and dix-/cent- prefixes for r = 1/2.
 */
function frDecimalOrdinal(place: number, singular: boolean): string {
  let word: string;
  if (place === 1) {
    word = "dixième";
  } else if (place === 2) {
    word = "centième";
  } else {
    const remainder = place % 3;
    const q = (place - remainder) / 3; // the power of 10^3 in the denominator
    let scale: string;
    if (q === 1) {
      scale = "mill"; // 10^-3 -> millième
    } else if (q % 2 === 0) {
      scale = illionName(q / 2).toLowerCase(); // 10^-6 millionième, 10^-12 billionième
    } else {
      // long-scale -iard: 10^-9 milliardième, 10^-15 billiardième ...
      scale = illionName((q - 1) / 2).toLowerCase().replace(/illion$/, "illiard");
    }
    const prefix = remainder === 1 ? "dix-" : remainder === 2 ? "cent-" : "";
    word = `${prefix}${scale}ième`;
  }
  return singular ? word : `${word}s`;
}

export const frLocale: LocaleDefinition = {
  code: "fr",
  zeroWord: "zéro",
  smallNumbers: FR_SMALL_NUMBERS,
  hundredWord: "cent",
  thousandWord: "mille",
  negativePrefix: "(négatif) ",
  dotSeparator: " (virgule) ",
  andStyle: "american", // French has no "and" join; remainder follows directly
  supportsBothStyles: false,
  groupSeparator: " ", // "cent vingt-trois millions quatre cent cinquante-six mille ..."
  scaleWordFor: frScaleWord,
  // "mille" alone (never "un mille"); larger thousands compose like any group
  // but with cent singular before mille ("deux cent mille", not "deux cents mille").
  thousandPhraseFor: (groupValue) => {
    if (groupValue === 1) {
      return "mille";
    }
    const hundreds = Math.floor(groupValue / 100);
    const remainder = groupValue % 100;
    const hundredsPart =
      hundreds === 0
        ? frSmall(remainder)
        : `${hundredPhrase(hundreds, remainder)}${remainder > 0 ? ` ${frSmall(remainder)}` : ""}`;
    return `${hundredsPart} mille`;
  },
  hundredPhraseFor: (hundreds, remainder) => hundredPhrase(hundreds, remainder),
  ordinalize: frOrdinalize,
  decimalOrdinal: frDecimalOrdinal,
};
