/**
 * Yorùbá locale (yo) - implemented in 4.3.0 from docs/locales/yo-SPEC.md
 * (sources quoted there: Wikipedia's Yoruba numerals analysis citing Lounge
 * 2009, Preply's lé-linker rule, Science in Yorùbá for òdo).
 *
 * The 0..99 system is the authentic mixed additive/subtractive vigesimal
 * logic: units 1-4 ADD to the decade anchor with "lé", units 5-9 SUBTRACT
 * from the next anchor with contracted dín-forms, and the fives have special
 * forms (ẹ̀ẹ́dọ́gbọ̀n = 25; aárùn-dínlógójì = 35; ...). Hundreds are the
 * traditional chain (igba, irinwó, ẹgbẹ̀ta, ẹgbẹ̀rin with ọ̀ọ́dúrún-style
 * subtractive neighbors). Thousands and beyond use the MODERN decimal
 * register (ẹgbẹ̀rún méjì - documented in the Wikipedia article) plus the
 * mílíọ̀nù/bílíọ̀nù loans, code-switching to English names beyond 10^9.
 *
 * Words for 0..99 are GENERATED by the rules below. Ordinals (periphrastic
 * in Yorùbá) and decimals reject loudly (SPEC §7); currency mode works.
 */

import { illionName } from "../illions.js";
import type { LocaleDefinition } from "./types.js";

const UNITS = [
  "ọ̀kan",
  "èjì",
  "ẹ̀ta",
  "ẹ̀rin",
  "àrún",
  "ẹ̀fà",
  "èje",
  "ẹ̀jọ",
  "ẹ̀sán",
] as const;

/** Decade anchors 20-100 with their contracted dín-forms (from the sources). */
const ANCHORS: readonly { base: number; word: string; dinForm: string }[] = [
  { base: 20, word: "ogún", dinForm: "lógún" },
  { base: 30, word: "ọgbọ̀n", dinForm: "lọ́gbọ̀n" },
  { base: 40, word: "ogójì", dinForm: "lógójì" },
  { base: 50, word: "àádọ́ta", dinForm: "làádọ́ta" },
  { base: 60, word: "ọgọ́ta", dinForm: "lọ́ta" },
  { base: 70, word: "àádọ́rin", dinForm: "làádọ́rin" },
  { base: 80, word: "ọgọ́rin", dinForm: "lọ́rin" },
  { base: 90, word: "àádọ́rùn-ún", dinForm: "làádọ́rùn-ún" },
  { base: 100, word: "ọgọ́rùn-ún", dinForm: "lọ̀rún-ún" },
];

/** Traditional hundreds 100-900 (SPEC §4). */
const HUNDREDS = [
  "ọgọ́rùn-ún",
  "igba",
  "ọ̀ọ́dúrún",
  "irinwó",
  "ẹ̀ẹ́dẹ́gbẹ̀ta",
  "ẹgbẹ̀ta",
  "ẹ̀ẹ́dẹ́gbẹ̀rin",
  "ẹgbẹ̀rin",
  "ẹ̀ẹ́dẹ́gbẹ̀rún",
] as const;

/** Object-numeral multipliers 1-10 (ẹgbẹ̀rún méjì, mílíọ̀nù márùn-ún, ...). */
const MULTIPLIERS = [
  "kan",
  "méjì",
  "mẹ́ta",
  "mẹ́rin",
  "márùn-ún",
  "mẹ́fà",
  "mèje",
  "mẹ́jọ",
  "mẹ́sàn-án",
  "mẹ́wá",
] as const;

/** Builds the 0..99 word table from the verified rules (SPEC §3). */
function buildSmallNumbers(): string[] {
  const table: string[] = [];

  table[0] = "òdo";
  UNITS.forEach((word, index) => {
    table[index + 1] = word;
  });

  table[10] = "ẹ̀wá";
  table[11] = "ọ̀kanlá";
  table[12] = "èjìlá";
  table[13] = "ẹ̀tàlá";
  table[14] = "ẹ̀rìnlá";
  table[15] = "ẹ̀ẹ́dógún"; // special: 5-from-20
  table[16] = "ẹ̀rìndínlógún";
  table[17] = "ẹ̀tàdínlógún";
  table[18] = "èjìdínlógún";
  table[19] = "ọ̀kàndínlógún";

  for (const [anchorIndex, anchor] of ANCHORS.entries()) {
    if (anchor.base === 100) {
      break; // 100 is a hundred word, not part of the 0..99 table
    }
    const next = ANCHORS[anchorIndex + 1] as { base: number; word: string; dinForm: string };

    table[anchor.base] = anchor.word;
    // Anchor+1..4: additive with lé
    UNITS.slice(0, 4).forEach((word, index) => {
      table[anchor.base + 1 + index] = `${anchor.word} lé ${word}`;
    });
    // Anchor-5: special five form (ẹ̀ẹ́dọ́gbọ̀n for 25; aárùn-dín... from 35 on)
    table[anchor.base + 5] = FIVE_FORMS[next.word] as string;
    // Anchor-4..1: subtractive with dín against the next anchor
    const subtractors = ["ẹ̀rìndín", "ẹ̀tàdín", "èjìdín", "ọ̀kàndín"];
    subtractors.forEach((prefix, index) => {
      table[anchor.base + 6 + index] = `${prefix}${next.dinForm}`;
    });
  }

  return table;
}

/** Special five forms keyed by the NEXT anchor's word (SPEC §3). */
const FIVE_FORMS: Record<string, string> = {
  ọgbọ̀n: "ẹ̀ẹ́dọ́gbọ̀n", // 25
  ogójì: "aárùn-dínlógójì", // 35
  àádọ́ta: "aárùn-dínlàádọ́ta", // 45
  ọgọ́ta: "aárùn-dínlọ́ta", // 55
  àádọ́rin: "aárùn-dínlàádọ́rin", // 65
  ọgọ́rin: "aárùn-dínlọ́rin", // 75
  "àádọ́rùn-ún": "aárùn-dínlàádọ́rùn-ún", // 85
  "ọgọ́rùn-ún": "aárùn-dínlọ̀rún-ún", // 95
};

/** Traditional hundreds phrase (SPEC §4). */
function yoHundreds(hundreds: number): string {
  return HUNDREDS[hundreds - 1] as string;
}

/** Multiplier word 1-10, or undefined above ten (juxtapose the group words). */
function yoMultiplier(value: number): string | undefined {
  return value >= 1 && value <= 10 ? (MULTIPLIERS[value - 1] as string) : undefined;
}

/** Scale loans + code-switch (SPEC §6): mílíọ̀nù/bílíọ̀nù, English beyond. */
function yoScaleWord(groupIndex: number, _groupValue: number, groupWords: string): string {
  const name =
    groupIndex === 2
      ? "mílíọ̀nù"
      : groupIndex === 3
        ? "bílíọ̀nù"
        : illionName(groupIndex - 1).toLowerCase();
  const multiplier = yoMultiplier(_groupValue) ?? groupWords;
  return `${name} ${multiplier}`;
}

export const yoLocale: LocaleDefinition = {
  code: "yo",
  zeroWord: "òdo",
  smallNumbers: buildSmallNumbers(),
  hundredWord: "ọgọ́rùn-ún",
  thousandWord: "ẹgbẹ̀rún",
  negativePrefix: "(negative) ", // OPEN ITEM (SPEC §7): unlocalized pending a source
  dotSeparator: "(dot) ", // unreachable - decimals are rejected (SPEC §7)
  andStyle: "american", // compounds juxtapose directly (no documented joiner)
  supportsBothStyles: false,
  groupSeparator: " ",
  scaleWordFor: yoScaleWord,
  thousandPhraseFor: (groupValue, groupWords) => {
    if (groupValue === 1) {
      return "ẹgbẹ̀rún"; // bare, per the sources
    }
    return `ẹgbẹ̀rún ${yoMultiplier(groupValue) ?? groupWords}`;
  },
  hundredPhraseFor: (hundreds) => yoHundreds(hundreds),
};
